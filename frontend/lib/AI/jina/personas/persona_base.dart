/// 페르소나 말투 타입
///
/// ## 종류
/// - `formal`: 격식체 (합니다)
/// - `polite`: 존댓말 (해요)
/// - `casual`: 반말 (해)
/// - `mixed`: 혼합 (상황에 따라)
enum PersonaTone {
  /// 격식체: "~합니다", "~입니다"
  /// 예: 선생님, 전문가
  formal,

  /// 존댓말: "~해요", "~예요"
  /// 예: 다정한 언니, 친절한 상담사
  polite,

  /// 반말: "~해", "~야"
  /// 예: 친구, 동생
  casual,

  /// 혼합: 상황에 따라 변경
  /// 예: 진지할 때 존댓말, 장난칠 때 반말
  mixed,
}

/// PersonaTone 확장 메서드
extension PersonaToneX on PersonaTone {
  /// 한글 표시 이름
  String get displayName {
    switch (this) {
      case PersonaTone.formal:
        return '격식체';
      case PersonaTone.polite:
        return '존댓말';
      case PersonaTone.casual:
        return '반말';
      case PersonaTone.mixed:
        return '혼합';
    }
  }

  /// 프롬프트에 포함할 설명
  String get promptDescription {
    switch (this) {
      case PersonaTone.formal:
        return '격식체(~합니다, ~입니다) 사용';
      case PersonaTone.polite:
        return '존댓말(~해요, ~예요) 사용';
      case PersonaTone.casual:
        return '반말(~해, ~야) 사용';
      case PersonaTone.mixed:
        return '상황에 따라 존댓말과 반말 혼용';
    }
  }
}

